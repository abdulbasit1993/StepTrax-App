package com.steptrax

import android.content.Context
import android.hardware.Sensor
import android.hardware.SensorEvent
import android.hardware.SensorEventListener
import android.hardware.SensorManager
import com.facebook.react.bridge.Arguments
import com.facebook.react.bridge.Promise
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.module.annotations.ReactModule
import java.util.concurrent.atomic.AtomicLong
import kotlin.math.sqrt

/**
 * TurboModule that counts steps with TYPE_STEP_DETECTOR (hardware, low power, one event per
 * step) and falls back to a debounced peak detector on TYPE_ACCELEROMETER.
 * NativeStepCounterSpec is generated by React Native codegen from src/specs/NativeStepCounter.ts.
 */
 @ReactModule(name = StepCounterModule.NAME)
 class StepCounterModule(reactContext: ReactApplicationContext) :
    NativeStepCounterSpec(reactContext), SensorEventListener {
        private val sensorManager =
            reactContext.getSystemService(Context.SENSOR_SERVICE) as
        SensorManager

        private val prefs = reactContext.getSharedPreferences(PREFS_NAME,
        Context.MODE_PRIVATE)

        private val steps = AtomicLong(0)
        @Volatile private var source = SOURCE_NONE

        // Accelerometer detector state (only touched on the sensor callback thread)
        private var gravity = SensorManager.GRAVITY_EARTH
        private var aboveThreshold = false
        private var lastStepMs = 0L

        override fun getName() = NAME

        override fun getSensorType(promise: Promise) {
            val type =
                when {
                    sensorManager.getDefaultSensor(Sensor.TYPE_STEP_DETECTOR) !=
                null -> SOURCE_DETECTOR
                    sensorManager.getDefaultSensor(Sensor.TYPE_ACCELEROMETER) !=
                null -> SOURCE_ACCEL
                    else -> SOURCE_NONE
                }
            promise.resolve(type)
        }

        override fun start(initialSteps: Double, forceAccelerometer: Boolean,
        promise: Promise) {
          sensorManager.unregisterListener(this)
          steps.set(initialSteps.toLong().coerceAtLeast(0L))
          resetAccelerometerState()

          val detector = 
            if (forceAccelerometer) null else
        sensorManager.getDefaultSensor(Sensor.TYPE_STEP_DETECTOR)
            val accelerometer = 
        sensorManager.getDefaultSensor(Sensor.TYPE_ACCELEROMETER)

            val sensor: Sensor?
            val name: String
            val rate: Int
            if (detector != null) {
                sensor = detector
                name = SOURCE_DETECTOR
                rate = SensorManager.SENSOR_DELAY_NORMAL
            } else if (accelerometer != null) {
                sensor = accelerometer
                name = SOURCE_ACCEL
                rate = SensorManager.SENSOR_DELAY_GAME // ~50 Hz, plenty for walking
            } else {
                sensor = null
                name = SOURCE_NONE
                rate = 0
            }

            if (sensor == null || !sensorManager.registerListener(this, sensor, rate)) {
                source = SOURCE_NONE
                promise.reject("E_NO_SENSOR", "No usable motion sensor on this device.")
                return
            }
            source = name
            promise.resolve(name)
        }

        override fun pause() {
            sensorManager.unregisterListener(this)
        }

        override fun reset() {
            steps.set(0)
            resetAccelerometerState()
            emit(0)
        }

        override fun getItem(key: String, promise: Promise) {
            promise.resolve(prefs.getString(key, "") ?: "")
        }

        override fun setItem(key: String, value: String) {
            prefs.edit().putString(key, value).apply()
        }

        override fun invalidate() {
            sensorManager.unregisterListener(this)
            super.invalidate()
        }

        override fun onSensorChanged(event: SensorEvent) {
            when (event.sensor.type) {
                Sensor.TYPE_STEP_DETECTOR -> addStep()
                Sensor.TYPE_ACCELEROMETER -> handleAccelerometer(event)
            }
        }

        override fun onAccuracyChanged(sensor: Sensor?, accuracy: Int) = Unit

        private fun handleAccelerometer(event: SensorEvent) {
            val x = event.values[0]
            val y = event.values[1]
            val z = event.values[2]
            val magnitude = sqrt(x * x + y * y + z * z)

            gravity = GRAVITY_ALPHA * gravity + (1 - GRAVITY_ALPHA) * magnitude
            val impulse = magnitude - gravity
            val nowMs = event.timestamp / 1_000_000L

            if (impulse > STEP_THRESHOLD) {
                if (!aboveThreshold && nowMs - lastStepMs >= MIN_STEP_INTERVAL_MS) {
                    lastStepMs = nowMs
                    addStep()
                }
                aboveThreshold = true
            } else if (impulse < STEP_THRESHOLD * 0.5f) {
                aboveThreshold = false
            }
        }

        private fun resetAccelerometerState() {
            gravity = SensorManager.GRAVITY_EARTH
            aboveThreshold = false
            lastStepMs = 0L
        }

        private fun addStep() {
            emit(steps.incrementAndGet())
        }

        private fun emit(total: Long) {
            val payload = Arguments.createMap()
            payload.putDouble("steps", total.toDouble())
            payload.putString("source", source)
            emitOnStepUpdate(payload)
        }

        companion object {
            const val NAME = "NativeStepCounter"
            private const val PREFS_NAME = "steptrax_store"

            private const val SOURCE_DETECTOR = "STEP_DETECTOR"
            private const val SOURCE_ACCEL = "ACCELEROMETER"
            private const val SOURCE_NONE = "NONE"

            private const val GRAVITY_ALPHA = 0.98f
            private const val STEP_THRESHOLD = 1.5f

            private const val MIN_STEP_INTERVAL_MS = 280L
        }
    }